//go:build ignore

// gentrigram builds trigram_table.go from a word list (e.g. /usr/share/dict/words).
//
//	go run gentrigram.go /usr/share/dict/words | gofmt > trigram_table.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

const pad = 26 // word start padding, and the "end of word" symbol in the next position

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run gentrigram.go <wordlist>")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	// Only plain lowercase words: skips proper nouns, acronyms and possessives
	re := regexp.MustCompile(`^[a-z]+$`)
	var counts [27 * 27][27]uint32
	words := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		w := sc.Text()
		if !re.MatchString(w) {
			continue
		}
		words++
		a, b := pad, pad
		for i := 0; i <= len(w); i++ {
			next := pad
			if i < len(w) {
				next = int(w[i] - 'a')
			}
			counts[a*27+b][next]++
			a, b = b, next
		}
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	fmt.Println("// Code generated by gentrigram.go; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package gen")
	fmt.Println()
	fmt.Printf("// trigramCounts[a*27+b][c] is how often letter c (26 = end of word) followed the letters a, b (26 = start of word)\n")
	fmt.Printf("// in %d dictionary words.\n", words)
	fmt.Println("var trigramCounts = [27 * 27][27]uint16{")
	for s, row := range counts {
		var sum uint32
		for _, v := range row {
			sum += v
		}
		if sum == 0 {
			continue
		}
		fmt.Printf("\t%d: {", s)
		for i, v := range row {
			if v > 0xFFFF {
				fmt.Fprintln(os.Stderr, "count overflows uint16")
				os.Exit(1)
			}
			if i > 0 {
				fmt.Print(", ")
			}
			fmt.Print(v)
		}
		fmt.Println("},")
	}
	fmt.Println("}")
}
